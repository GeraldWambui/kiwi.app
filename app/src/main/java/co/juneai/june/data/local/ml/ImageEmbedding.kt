package co.juneai.june.data.local.ml

import io.objectbox.annotation.Entity
import io.objectbox.annotation.HnswIndex
import io.objectbox.annotation.Id
import io.objectbox.annotation.Index
import io.objectbox.annotation.VectorDistanceType

/**
 * ObjectBox entity storing one indexed image and its CLIP embedding.
 *
 * The [embedding] property carries an [HnswIndex] which instructs ObjectBox to build
 * an HNSW (Hierarchical Navigable Small World) graph on this vector column at write time.
 * Nearest-neighbor queries then run in O(log N) rather than O(N × DIM).
 *
 * HNSW parameter guide:
 *  dimensions          = 512   CLIP ViT-B/32 output size — must match exactly.
 *  neighborsPerNode    = 30    M: graph fan-out per node. 16–48 is the practical range;
 *                              30 gives good recall/memory balance for 512-dim vectors.
 *  indexingSearchCount = 100   efConstruction: candidates examined while building each node.
 *                              Higher → better recall at the cost of slower index builds.
 *                              100 is safe for production; raise to 200 for higher accuracy.
 *  distanceType        = COSINE Correct for L2-normalized CLIP embeddings. ObjectBox
 *                              cosine distance ∈ [0, 2]: 0 = identical, 2 = opposite.
 *
 * [mediaStoreId] carries an [Index] so existence checks and prune queries are O(log N)
 * BTree lookups rather than full scans.
 *
 * NOTE: [MyObjectBox] and [ImageEmbedding_] are generated by the ObjectBox Gradle plugin
 * on the first build. Run `./gradlew kaptDebugKotlin` (kapt) or `./gradlew kspDebugKotlin`
 * (KSP) if they are missing after adding this entity.
 */
@Entity
data class ImageEmbedding(

    @Id
    var id: Long = 0,

    /** MediaStore._ID — the stable device identifier for this image file. */
    @Index
    var mediaStoreId: Long = 0,

    var uri: String = "",
    var displayName: String = "",

    @HnswIndex(
        dimensions          = 512,
        neighborsPerNode    = 30,
        indexingSearchCount = 100,
        distanceType        = VectorDistanceType.COSINE,
    )
    var embedding: FloatArray = FloatArray(512),

    /** Unix millis when this row was indexed — useful for incremental re-index strategies. */
    var indexedAt: Long = 0L,
) {
    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (javaClass != other?.javaClass) return false

        other as ImageEmbedding

        if (id != other.id) return false
        if (mediaStoreId != other.mediaStoreId) return false
        if (indexedAt != other.indexedAt) return false
        if (uri != other.uri) return false
        if (displayName != other.displayName) return false
        if (!embedding.contentEquals(other.embedding)) return false

        return true
    }

    override fun hashCode(): Int {
        var result = id.hashCode()
        result = 31 * result + mediaStoreId.hashCode()
        result = 31 * result + indexedAt.hashCode()
        result = 31 * result + uri.hashCode()
        result = 31 * result + displayName.hashCode()
        result = 31 * result + embedding.contentHashCode()
        return result
    }
}